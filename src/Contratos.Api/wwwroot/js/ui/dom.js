// Montagem de DOM sem innerHTML: dados do usuário entram sempre como texto.

/**
 * h('a', { href: '/x', class: 'btn', onclick: fn, dataset: { id: 1 } }, 'texto', filho)
 * Atributos null/undefined/false são omitidos; true vira atributo vazio.
 */
export function h(tag, attrs = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs ?? {})) {
    if (value === null || value === undefined || value === false) continue;
    if (key.startsWith('on') && typeof value === 'function') el.addEventListener(key.slice(2), value);
    else if (key === 'dataset') Object.assign(el.dataset, value);
    else if (key === 'class') el.className = value;
    else if (key in el && typeof value !== 'string') el[key] = value;
    else el.setAttribute(key, value === true ? '' : String(value));
  }
  append(el, children);
  return el;
}

function append(el, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
}

/** SVG a partir de marcação fixa do próprio código (nunca de dados do usuário). */
export function icon(markup) {
  const tpl = document.createElement('template');
  tpl.innerHTML = markup.trim();
  return tpl.content.firstElementChild;
}

export function clear(el) {
  el.replaceChildren();
  return el;
}

